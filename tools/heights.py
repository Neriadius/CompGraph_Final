"""Height maps of the imported models for the snow (Person 3).

For every grid point over a model's x/z footprint, a ray is cast straight down and the
highest surface hit is stored (cut-out texture pixels with alpha < 0.5 are ignored, so
snow does not rest on the invisible corners of the pine branch cards).
Output: src/ModelHeights.h, used by SurfaceHeightAt (via InteriorLayout.h).

usage: python3 tools/heights.py <models dir> <output header>
"""
import os
import sys

import numpy as np
from PIL import Image


def read_obj(path):
    folder = os.path.dirname(path)
    V, T, tris, mats, cur = [], [], [], {}, None
    with open(path) as f:
        for line in f:
            p = line.split()
            if not p:
                continue
            if p[0] == 'v':
                V.append([float(x) for x in p[1:4]])
            elif p[0] == 'vt':
                T.append([float(x) for x in p[1:3]])
            elif p[0] == 'usemtl':
                cur = p[1]
            elif p[0] == 'f':
                idx = [[int(x) - 1 for x in q.split('/')[:2]] for q in p[1:4]]
                tris.append((idx, cur))
            elif p[0] == 'mtllib':
                name = None
                for ml in open(os.path.join(folder, p[1])):
                    q = ml.split()
                    if q and q[0] == 'newmtl':
                        name = q[1]
                        mats[name] = None
                    elif q and q[0] == 'map_d':
                        a = np.asarray(Image.open(os.path.join(folder, q[1])).convert('RGBA'))[:, :, 3]
                        mats[name] = a
    return np.array(V), np.array(T), tris, mats


def height_map(path, n, pad=0.01):
    V, T, tris, mats = read_obj(path)
    lo, hi = V[:, [0, 2]].min(0) - pad, V[:, [0, 2]].max(0) + pad
    cell = float(max(hi - lo) / (n - 1))
    xs = lo[0] + cell * np.arange(n)
    zs = lo[1] + cell * np.arange(n)
    GX, GZ = np.meshgrid(xs, zs)                      # [iz, ix]
    H = np.full(GX.shape, -1.0)
    for idx, mat in tris:
        p = V[[i for i, _ in idx]]
        a, b, c = p[:, [0, 2]]
        x0, z0 = np.minimum(np.minimum(a, b), c)
        x1, z1 = np.maximum(np.maximum(a, b), c)
        ix = np.where((xs >= x0) & (xs <= x1))[0]
        iz = np.where((zs >= z0) & (zs <= z1))[0]
        if len(ix) == 0 or len(iz) == 0:
            continue
        px, pz = np.meshgrid(xs[ix], zs[iz])
        d = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1])
        if abs(d) < 1e-14:
            continue
        w0 = ((b[1] - c[1]) * (px - c[0]) + (c[0] - b[0]) * (pz - c[1])) / d
        w1 = ((c[1] - a[1]) * (px - c[0]) + (a[0] - c[0]) * (pz - c[1])) / d
        w2 = 1 - w0 - w1
        inside = (w0 >= 0) & (w1 >= 0) & (w2 >= 0)
        if not inside.any():
            continue
        y = w0 * p[0, 1] + w1 * p[1, 1] + w2 * p[2, 1]
        alpha = mats.get(mat)
        if alpha is not None:
            uv = T[[t for _, t in idx]]
            u = w0 * uv[0, 0] + w1 * uv[1, 0] + w2 * uv[2, 0]
            v = w0 * uv[0, 1] + w1 * uv[1, 1] + w2 * uv[2, 1]
            hgt, wid = alpha.shape
            col = np.clip(((u % 1.0) * wid).astype(int), 0, wid - 1)
            row = np.clip(((1.0 - v % 1.0) * hgt).astype(int), 0, hgt - 1)
            inside &= alpha[row, col] >= 128
        sub = H[np.ix_(iz, ix)]
        H[np.ix_(iz, ix)] = np.where(inside, np.maximum(sub, y), sub)
    return lo, cell, H


def main():
    models, out = sys.argv[1], sys.argv[2]
    fields = [('HUT', 'hut/hut.obj', 56), ('PINE', 'trees/pine.obj', 28),
              ('PINE_TALL', 'trees/pine_tall.obj', 28), ('SHRUB', 'trees/shrub.obj', 14)]
    lines = ['#ifndef MODEL_HEIGHTS_H', '#define MODEL_HEIGHTS_H', '',
             '// GENERATED by tools/heights.py from the OBJ files in models/ - do not edit by hand.',
             '// Top surface of each model (model units, -1 = nothing there) on a grid over its x/z',
             '// footprint, so falling snow can rest on the roof and on the pine branches.', '',
             '#include <algorithm>', '#include <cmath>', '', 'namespace heights', '{',
             '\tstruct Field { float x0, z0, cell; int nx, nz; const float* data; };', '']
    for name, rel, n in fields:
        lo, cell, H = height_map(os.path.join(models, rel), n)
        vals = ', '.join(f'{v:.4f}' if v >= 0 else '-1' for v in H.ravel())
        lines += [f'\t// {rel}: {n} x {n} cells of {cell:.4f}',
                  f'\tinline constexpr float {name}_DATA[] = {{ {vals} }};',
                  f'\tinline constexpr Field {name} = {{ {lo[0]:.4f}f, {lo[1]:.4f}f, {cell:.5f}f, {n}, {n}, {name}_DATA }};', '']
        print(f'{name}: covered {(H >= 0).mean() * 100:.0f}% of the grid, max {H.max():.3f}')
    lines += ['\t// Height at (x, z) in model units: bilinear inside the surface, nearest at its edges, -1 outside',
              '\tinline float Sample(const Field& f, float x, float z)',
              '\t{',
              '\t\tfloat gx = (x - f.x0) / f.cell, gz = (z - f.z0) / f.cell;',
              '\t\tif (gx < 0.0f || gz < 0.0f || gx > f.nx - 1 || gz > f.nz - 1) return -1.0f;',
              '\t\tint ix = std::min((int)gx, f.nx - 2), iz = std::min((int)gz, f.nz - 2);',
              '\t\tfloat tx = gx - ix, tz = gz - iz;',
              '\t\tfloat h00 = f.data[iz * f.nx + ix], h10 = f.data[iz * f.nx + ix + 1];',
              '\t\tfloat h01 = f.data[(iz + 1) * f.nx + ix], h11 = f.data[(iz + 1) * f.nx + ix + 1];',
              '\t\tif (h00 >= 0.0f && h10 >= 0.0f && h01 >= 0.0f && h11 >= 0.0f)',
              '\t\t\treturn (h00 * (1 - tx) + h10 * tx) * (1 - tz) + (h01 * (1 - tx) + h11 * tx) * tz;',
              '\t\tint nx = ix + (tx > 0.5f ? 1 : 0), nz = iz + (tz > 0.5f ? 1 : 0);',
              '\t\treturn f.data[nz * f.nx + nx];',
              '\t}', '}', '', '#endif', '']
    with open(out, 'w', newline='\n') as fh:
        fh.write('\n'.join(lines))


if __name__ == '__main__':
    main()
