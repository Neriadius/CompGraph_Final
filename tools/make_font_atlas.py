"""Bake the menu fonts into a signed distance field (SDF) atlas.

    python3 tools/make_font_atlas.py <title font> <body font> <bold font> textures/ui_font.png textures/ui_font.txt

Used fonts (SIL Open Font License, see CREDITS.md):
    title  Cormorant Garamond SemiBold (600)
    body   Inter Medium (500)
    bold   Inter SemiBold (600)
TTF, OTF or WOFF files all work (Pillow / FreeType). Needs numpy, scipy and Pillow with raqm
(for kerning).

Each glyph is drawn 4x larger, the distance to the outline is measured on that big bitmap
(scipy distance transform), and then averaged down. The PNG stores 0.5 + distance / (2 * spread):
0.5 is the outline, brighter is inside. The shader turns that distance into a sharp, smooth edge
at any size, and into a soft glow outside the letters.
"""
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import distance_transform_edt

SS = 4                                   # supersampling for the distance measurement
ATLAS_W = 1024
EXTRA = "·–—−"       # middle dot, en dash, em dash, minus sign
ASCII = "".join(chr(c) for c in range(32, 127))

# name, em size in atlas pixels, distance range (spread) in atlas pixels, characters
FACES = [
    ("TITLE", 72, 12, ASCII),
    ("BODY", 40, 6, ASCII + EXTRA),
    ("BOLD", 40, 6, ASCII + EXTRA),
]
FEATURES = ["kern", "-liga", "-calt"]


def bake_glyph(font, ch, em, spread):
    """Returns (sdf uint8 image or None, quad in em units, advance in em units)."""
    advance = font.getlength(ch, features=FEATURES) / (em * SS)
    box = font.getbbox(ch, anchor="ls", features=FEATURES)
    if box[2] <= box[0] or box[3] <= box[1]:
        return None, None, advance

    pad = spread + 1                                 # atlas pixels around the ink
    x0 = int(np.floor(box[0] / SS)) - pad
    y0 = int(np.floor(box[1] / SS)) - pad
    x1 = int(np.ceil(box[2] / SS)) + pad
    y1 = int(np.ceil(box[3] / SS)) + pad
    w, h = x1 - x0, y1 - y0

    big = Image.new("L", (w * SS, h * SS), 0)
    ImageDraw.Draw(big).text((-x0 * SS, -y0 * SS), ch, font=font, fill=255,
                             anchor="ls", features=FEATURES)
    inside = np.asarray(big) >= 128
    dist_in = distance_transform_edt(inside)
    dist_out = distance_transform_edt(~inside)
    signed = np.where(inside, dist_in - 0.5, 0.5 - dist_out) / SS    # atlas pixels, + inside
    signed = signed.reshape(h, SS, w, SS).mean(axis=(1, 3))
    value = np.clip(0.5 + signed / (2.0 * spread), 0.0, 1.0)
    sdf = (value * 255.0 + 0.5).astype(np.uint8)
    quad = (x0 / em, y0 / em, x1 / em, y1 / em)       # y down, baseline at 0
    return sdf, quad, advance


def kerning(font, chars, em):
    pairs = []
    letters = [c for c in chars if c != " "]
    single = {c: font.getlength(c, features=FEATURES) for c in letters}
    for a in letters:
        for b in letters:
            k = (font.getlength(a + b, features=FEATURES) - single[a] - single[b]) / (em * SS)
            if abs(k) > 0.006:
                pairs.append((ord(a), ord(b), k))
    return pairs


def main():
    if len(sys.argv) != 6:
        print(__doc__)
        sys.exit(1)
    font_paths = sys.argv[1:4]
    out_png, out_metrics = sys.argv[4], sys.argv[5]

    baked = []                                        # (face index, char, sdf, quad, advance)
    face_info = []
    for index, ((name, em, spread, chars), path) in enumerate(zip(FACES, font_paths)):
        font = ImageFont.truetype(path, em * SS, layout_engine=ImageFont.Layout.RAQM)
        ascent, descent = font.getmetrics()
        face_info.append({
            "name": name, "em": em, "spread": spread,
            "ascent": ascent / (em * SS), "descent": descent / (em * SS),
            "kerns": kerning(font, chars, em),
        })
        for ch in chars:
            sdf, quad, advance = bake_glyph(font, ch, em, spread)
            baked.append((index, ch, sdf, quad, advance))

    # Shelf packing, tallest glyphs first.
    order = sorted(range(len(baked)),
                   key=lambda i: -(baked[i][2].shape[0] if baked[i][2] is not None else 0))
    places = {}
    x = y = shelf = 0
    for i in order:
        sdf = baked[i][2]
        if sdf is None:
            continue
        h, w = sdf.shape
        if x + w > ATLAS_W:
            x, y, shelf = 0, y + shelf + 1, 0
        places[i] = (x, y)
        x += w + 1
        shelf = max(shelf, h)
    atlas_h = y + shelf + 1
    atlas_h = (atlas_h + 3) // 4 * 4
    atlas = np.zeros((atlas_h, ATLAS_W), np.uint8)
    for i, (px, py) in places.items():
        sdf = baked[i][2]
        atlas[py:py + sdf.shape[0], px:px + sdf.shape[1]] = sdf
    Image.fromarray(atlas, "L").save(out_png, optimize=True)

    # Texture.cpp flips rows (OpenGL: first row = bottom), so v = 1 - y / height.
    lines = [
        "# GENERATED by tools/make_font_atlas.py - metrics for textures/ui_font.png (SDF atlas).",
        "# face <index> <em px> <spread px> <ascent> <descent>          (em units)",
        "# glyph <face> <code> <x0 y0 x1 y1> <u0 v0 u1 v1> <advance>    (quad in em, y down, baseline 0)",
        "# kern <face> <left code> <right code> <amount in em>",
        f"atlas {ATLAS_W} {atlas_h}",
    ]
    for index, info in enumerate(face_info):
        lines.append(f"face {index} {info['em']} {info['spread']} {info['ascent']:.5f} {info['descent']:.5f}")
    for i, (face, ch, sdf, quad, advance) in enumerate(baked):
        if sdf is None:
            lines.append(f"glyph {face} {ord(ch)} 0 0 0 0 0 0 0 0 {advance:.5f}")
            continue
        px, py = places[i]
        h, w = sdf.shape
        u0, u1 = px / ATLAS_W, (px + w) / ATLAS_W
        v0, v1 = 1.0 - py / atlas_h, 1.0 - (py + h) / atlas_h
        q = quad
        lines.append(f"glyph {face} {ord(ch)} {q[0]:.5f} {q[1]:.5f} {q[2]:.5f} {q[3]:.5f} "
                     f"{u0:.6f} {v0:.6f} {u1:.6f} {v1:.6f} {advance:.5f}")
    for index, info in enumerate(face_info):
        for a, b, k in info["kerns"]:
            lines.append(f"kern {index} {a} {b} {k:.5f}")
    with open(out_metrics, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out_png}: {ATLAS_W}x{atlas_h}, {len(places)} glyphs; {out_metrics} written")


if __name__ == "__main__":
    main()
